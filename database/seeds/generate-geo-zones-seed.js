#!/usr/bin/env node
/**
 * generate-geo-zones-seed.js
 *
 * Reads Ecuador administrative-boundary GeoJSON geometries and emits raw SQL
 * INSERT statements for the `geo_zones` table (T1.5), scoped to Santa Elena
 * province (EC-24) and its 3 cantons (EC-24-01/02/03).
 *
 * This script is NOT run automatically as part of any migration pipeline —
 * per CC3 (Manual Migration Integrity) all schema/data changes are applied
 * manually by a human via the Supabase SQL editor. The script's OUTPUT (a
 * .sql file) is what gets committed and pasted manually; the script itself
 * is a one-time generator, kept for reproducibility/audit.
 *
 * Usage:
 *   node database/seeds/generate-geo-zones-seed.js \
 *     <path-to-ecuador-locations-geom.json> \
 *     > database/seeds/0003_seed_geo_zones.generated.sql
 *
 * Geometry note: EC-24 and its cantons are MultiPolygon in the source data
 * (verified: EC-24 bounds lng[-81.008,-80.200] lat[-2.508,-1.669], 647
 * points) — the `geo_zones.polygon` column MUST be
 * `geometry(MultiPolygon, 4326)`, not `geometry(Polygon, 4326)`.
 */
'use strict';

const fs = require('fs');
const path = require('path');

// Fixed, deterministic UUIDs (NOT randomly regenerated on each run) so the
// seed is idempotent/reproducible and other tables/config
// (GEO_DEFAULT_ZONE_ID) can reference a stable id.
const ZONE_IDS = {
  'EC-24': '8f14e45f-ceea-4c1f-8f2c-000000000024', // Santa Elena (province)
  'EC-24-01': '8f14e45f-ceea-4c1f-8f2c-000000000101', // Santa Elena (canton)
  'EC-24-02': '8f14e45f-ceea-4c1f-8f2c-000000000102', // La Libertad (canton)
  'EC-24-03': '8f14e45f-ceea-4c1f-8f2c-000000000103', // Salinas (canton)
};

const ZONE_NAMES = {
  'EC-24': 'Santa Elena (Provincia)',
  'EC-24-01': 'Santa Elena (Cantón)',
  'EC-24-02': 'La Libertad',
  'EC-24-03': 'Salinas',
};

function main() {
  const inputPath = process.argv[2];
  if (!inputPath) {
    // eslint-disable-next-line no-console
    console.error(
      'Usage: node generate-geo-zones-seed.js <path-to-ecuador-locations-geom.json>',
    );
    process.exit(1);
  }

  const raw = fs.readFileSync(path.resolve(inputPath), 'utf8');
  const data = JSON.parse(raw);

  const keys = Object.keys(ZONE_IDS);
  const missing = keys.filter((k) => !data[k]);
  if (missing.length > 0) {
    throw new Error(`Missing expected keys in source GeoJSON: ${missing.join(', ')}`);
  }

  const lines = [];
  lines.push('-- Generated by database/seeds/generate-geo-zones-seed.js — DO NOT EDIT BY HAND.');
  lines.push('-- Source: GeoReporta/backend/database/data/ecuador-locations-geom.json (EC-24 + cantons).');
  lines.push('-- Paste this into 0002_add_postgis_and_geo_zones.sql (or run standalone after it).');
  lines.push('');

  for (const key of keys) {
    const geometry = data[key];
    if (geometry.type !== 'MultiPolygon') {
      throw new Error(`Expected MultiPolygon for ${key}, got ${geometry.type}`);
    }
    const geojsonText = JSON.stringify(geometry);
    const id = ZONE_IDS[key];
    const name = ZONE_NAMES[key].replace(/'/g, "''");

    lines.push(
      `INSERT INTO geo_zones (id, name, polygon, active) VALUES (`,
      `  '${id}',`,
      `  '${name}',`,
      `  ST_SetSRID(ST_GeomFromGeoJSON($geojson$${geojsonText}$geojson$), 4326),`,
      `  true`,
      `) ON CONFLICT (id) DO NOTHING;`,
      '',
    );
  }

  process.stdout.write(lines.join('\n') + '\n');
}

main();
